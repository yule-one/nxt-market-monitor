from __future__ import annotations

import base64
import hashlib
import hmac
import os
import re
import sqlite3
import threading
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Mapping

try:
    import psycopg
    from psycopg.rows import dict_row
except ImportError:  # PostgreSQL is optional for local SQLite-only development.
    psycopg = None
    dict_row = None


PBKDF2_ALGORITHM = "sha256"
PBKDF2_ITERATIONS = 600_000
PASSWORD_SCHEME = "pbkdf2_sha256"
MAX_FAILED_ATTEMPTS = 5
LOCK_MINUTES = 15
USERNAME_PATTERN = re.compile(r"^[a-z0-9._-]{3,32}$")
VALID_ROLES = {"admin", "user"}


class AuthError(ValueError):
    """Raised when an account operation cannot be completed safely."""


class PasswordPolicyError(AuthError):
    """Raised when a password does not meet the local password policy."""


class AuthConfigurationError(AuthError):
    """Raised when the configured authentication database is unavailable."""


@dataclass(frozen=True)
class AuthUser:
    id: int
    username: str
    display_name: str
    role: str
    is_active: bool
    must_change_password: bool
    failed_attempts: int
    locked_until: datetime | None
    created_at: datetime
    updated_at: datetime
    last_login_at: datetime | None

    @property
    def is_admin(self) -> bool:
        return self.role == "admin"


@dataclass(frozen=True)
class AuditEvent:
    id: int
    actor_username: str
    action: str
    target_username: str
    detail: str
    created_at: datetime


@dataclass(frozen=True)
class MigrationResult:
    users: int
    audit_events: int


